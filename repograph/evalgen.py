"""Generate retrieval questions with ground truth, from the repo itself.

    python repograph/evalgen.py IDX -o questions.json
    python repograph/repograph.py IDX eval questions.json

Why this exists: every ranking question in this project has died the same way --
a hand-written set of thirty questions cannot resolve a six-point difference.
Hand-written sets stay the instrument of judgment, because only a person asks
questions the way a person asks them. This is the instrument of *tuning*, and it
scales with the repository instead of with an afternoon.

Three generators, each labelled in the output, because they carry different
biases and pooling them hides that:

    module-doc   a file's own `//!` header, ground truth that file
    doc-split    an item's first doc sentence, ground truth its file
    test-name    the words in a `#[test]` name, ground truth its file

Every generated question holds out exactly the text it was generated from. That
is not optional: a question drawn from a file's module doc, asked against an
index containing that module doc, scores 66% and measures string matching
against itself, while removing the text entirely scores 1% and measures nothing
at all. Both were measured. The holdout is what makes it a question.

`test-name` is the one generator that needs no holdout, because test symbols are
excluded from ranking anyway, and the only one that survives undocumented code.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import repograph as RG  # noqa: E402

SENT = re.compile(r'(?<=[.!?])\s+')
TEST_PREFIX = re.compile(r'^(test|it|should|check)[_\s]*', re.I)


def first_sentence(text):
    parts = [p for p in SENT.split((text or '').strip()) if p.strip()]
    if not parts:
        return None, None
    return parts[0], ' '.join(parts[1:])


def clean(text):
    """Strip markdown and doc-link noise so a generated question reads like
    something a person would type rather than like rustdoc."""
    text = re.sub(r'\[`?([^\]`]+)`?\]\([^)]*\)', r'\1', text or '')
    text = re.sub(r'[`\[\]#*|<>]', ' ', text)
    return ' '.join(text.split())


def from_modules(idx):
    out = []
    lib = {s['file'] for s in idx.symbols if s.get('role', 'lib') == 'lib'}
    for f, md in sorted(idx.modules.items()):
        if f not in lib:
            continue
        head, rest = first_sentence(clean(md))
        if not head or len(RG.tokens(head)) < 3:
            continue
        out.append({
            'q': head[:160],
            'ok': [f],
            'src': 'module-doc',
            'hold': {'file': f, 'rest': rest[:600]},
        })
    return out


def from_docs(idx, limit=400):
    out = []
    for i, s in enumerate(idx.symbols):
        if s.get('test') or not s['doc'] or s.get('role', 'lib') != 'lib':
            continue
        head, rest = first_sentence(clean(s['doc']))
        if not head or not rest:
            continue
        own = set(RG.tokens(s['name']))
        qt = [t for t in RG.tokens(head) if t not in own]
        if len(qt) < 4:
            continue
        out.append({
            'q': head[:160],
            'ok': [s['file']],
            'src': 'doc-split',
            'hold': {'file': s['file'], 'line': s['line'], 'rest': rest[:600]},
        })
        if len(out) >= limit:
            break
    return out


def from_tests(idx):
    """`fn test_date_add_assign` -> "date add assign". The test sits in the
    file it exercises, so the file is the answer, and none of this depends on
    anybody having written documentation."""
    lib = {s['file'] for s in idx.symbols if s.get('role', 'lib') == 'lib'}
    out, seen = [], set()
    for t in idx.tests:
        if t['file'] not in lib:
            continue
        name = TEST_PREFIX.sub('', t['name'])
        words = RG.tokens(name)
        if len(words) < 2:
            continue
        q = ' '.join(words)
        if q in seen:
            continue
        seen.add(q)
        out.append({'q': q, 'ok': [t['file']], 'src': 'test-name', 'hold': {}})
    return out


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 1
    idxpath = argv[1]
    out = None
    if '-o' in argv:
        out = argv[argv.index('-o') + 1]
    idx = RG.Index(idxpath)

    qs = from_modules(idx) + from_docs(idx) + from_tests(idx)
    # Ground truth must be a file the index actually holds, or a question is
    # unanswerable for reasons that have nothing to do with ranking.
    # Ground truth has to be somewhere the ranker can actually return, or a
    # question is unanswerable for reasons that have nothing to do with
    # ranking. Benchmarks and integration tests are indexed but not ranked.
    files = {s['file'] for s in idx.symbols if s.get('role', 'lib') == 'lib'}
    qs = [q for q in qs if all(f in files for f in q['ok'])]

    payload = {
        'note': ('Generated by evalgen.py from the repository itself. For '
                    'TUNING at scale, not for judgment -- a hand-written set is '
                    'the only thing that asks questions the way a person does. '
                    'Every question holds out the text it came from; see the '
                    'module docstring for why that is not optional. Stratify by '
                    '"src" before concluding anything: the three generators have '
                    'different biases.'),
        'repo': idx.meta.get('name'),
        'questions': qs,
    }
    counts = {}
    for q in qs:
        counts[q['src']] = counts.get(q['src'], 0) + 1
    if out:
        with open(out, 'w', encoding='utf-8') as fh:
            json.dump(payload, fh, indent=4)
        print('%d questions -> %s' % (len(qs), out))
    else:
        print(json.dumps(payload, indent=4))
        return 0
    for k, v in sorted(counts.items()):
        print('    %-12s %d' % (k, v))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
